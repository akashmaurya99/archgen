// sandbox.mjs — a complete, valid archgen project in a temp directory.
//
// WHY A HELPER: the action-matrix gate drives EVERY action of EVERY tool, and
// a tool that only works against a half-built project proves nothing. Every
// test that needs "a project archgen can work on" builds it here, so the
// fixture shape can never drift between tests.
//
// The shape is the canonical one from the depth ladder:
//   .archgen/<slug>/tasks.yaml        — the task graph
//   .archgen/<slug>/plans/*.md        — the plan (every task id is named)
//   .archgen/<slug>/docs/*.md         — the prose artifacts
//   .archgen/<slug>/decisions/*.md    — the ADRs
//   AGENTS.md                         — the features registry
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

export const SLUG = 'demo';

const TASKS = `# generated by archgen — sandbox fixture
tasks:
  - id: SCAFFOLD
    title: Scaffold project skeleton and typed config loading
    depends_on: []
    file_ownership: ["src/config/**"]
    acceptance:
      - "npm run build exits 0"
  - id: SHARED
    title: Implement shared logging and error envelope helpers
    depends_on: [SCAFFOLD]
    file_ownership: ["src/shared/**"]
    acceptance:
      - "logger emits structured json lines"
  - id: API
    title: Notes REST API with validation
    depends_on: [SCAFFOLD, SHARED]
    file_ownership: ["src/features/api/**"]
    acceptance:
      - "GET /notes returns the seeded list"
  - id: WEB
    title: Admin console pages wired to the API client
    depends_on: [SCAFFOLD, SHARED]
    file_ownership: ["src/features/web/**"]
    acceptance:
      - "console renders the notes list from the live API"
  - id: VERIFY
    title: End-to-end smoke suite across api and web
    depends_on: [API, WEB]
    file_ownership: ["tests/e2e/**"]
    acceptance:
      - "smoke suite completes the happy path"
`;

