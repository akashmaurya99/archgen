/**
 * Build a sandbox project.
 *
 * @param {{keep?: boolean}} [opts]
 * @returns {{root: string, slug: string, slugDir: string, plansDir: string, docsDir: string, tasksYaml: string, cleanup: () => void}}
 */
export function buildSandbox(opts = {}) {
  const root = mkdtempSync(join(tmpdir(), 'archgen-sandbox-'));
  const slugDir = join(root, '.archgen', SLUG);
  const plansDir = join(slugDir, 'plans');
  const docsDir = join(slugDir, 'docs');
  mkdirSync(plansDir, { recursive: true });
  mkdirSync(docsDir, { recursive: true });
  mkdirSync(join(slugDir, 'decisions'), { recursive: true });

  writeFileSync(join(slugDir, 'tasks.yaml'), TASKS, 'utf8');
  writeFileSync(join(plansDir, 'demo-platform.md'), PLAN, 'utf8');
  writeFileSync(join(docsDir, 'prd.md'), PRD, 'utf8');
  writeFileSync(join(docsDir, 'user-guide.md'), GUIDE, 'utf8');
  writeFileSync(join(slugDir, 'decisions', '0001-local-services.md'), ADR, 'utf8');
  writeFileSync(join(root, 'AGENTS.md'), AGENTS, 'utf8');

  return {
    root,
    slug: SLUG,
    slugDir,
    plansDir,
    docsDir,
    tasksYaml: join(slugDir, 'tasks.yaml'),
    cleanup: () => {
      if (!opts.keep) rmSync(root, { recursive: true, force: true });
    },
  };
}
